function pexelsUrl(id) {
  return `https://images.pexels.com/photos/${id}/pexels-photo-${id}.jpeg?auto=compress&cs=tinysrgb&w=640&h=512&fit=crop`;
}

function curlSize(url) {
  const tmp = join(root, "_curl_test.jpg");
  try {
    execSync(`curl.exe -sL -A "Mozilla/5.0" "${url}" -o "${tmp}"`, { stdio: "pipe" });
    const size = statSync(tmp).size;
    unlinkSync(tmp);
    return size;
  } catch {
    return 0;
  }
}

