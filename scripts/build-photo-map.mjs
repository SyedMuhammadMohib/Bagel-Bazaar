const used = new Set();
const photos = {};
let poolIdx = 0;

function takeVerified(preferred) {
  if (typeof preferred === "string") return preferred;
  if (preferred && !used.has(preferred)) {
    const v = verified.find((x) => x.id === preferred);
    if (v) {
      used.add(preferred);
      return v.url;
    }
  }
  while (poolIdx < verified.length) {
    const v = verified[poolIdx++];
    if (!used.has(v.id)) {
      used.add(v.id);
      return v.url;
    }
  }
  throw new Error("Pool exhausted");
}

for (const key of keys) {
  photos[key] = takeVerified(SEMANTIC_PEXELS[key]);
}

